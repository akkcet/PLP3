class DirectoryWatcher(PilotSDKComponent):
    """
    A Pipeline Pilot component that scans a specified directory for files
    matching a glob pattern and outputs their absolute paths.

    This component is designed to find relevant files (e.g., XML uploads)
    at the start of a workflow, enabling subsequent components to process them.
    """
    def main(self):
        """
        The main execution method for the Directory Watcher component.
        It retrieves parameters, validates the directory, scans for files,
        and outputs the absolute paths of matching files.
        """
        directory_path = self.get_parameter('DirectoryPath')
        file_pattern = self.get_parameter('FilePattern')
        process_subdirectories = self.get_parameter('ProcessSubdirectories')

        if not directory_path:
            self.logger.error("DirectoryPath parameter cannot be empty.")
            raise ValueError("DirectoryPath parameter is required and cannot be empty.")

        # Resolve the directory path to an absolute path for robustness.
        # This handles relative paths correctly based on the component's execution context.
        absolute_directory_path = os.path.abspath(directory_path)

        if not os.path.isdir(absolute_directory_path):
            self.logger.error(f"Specified directory does not exist or is not a directory: '{absolute_directory_path}'")
            raise FileNotFoundError(f"Directory not found: '{absolute_directory_path}'")

        self.logger.info(
            f"Starting scan of directory: '{absolute_directory_path}' "
            f"with pattern: '{file_pattern}' (recursive: {process_subdirectories})"
        )

        # Construct the search path for glob, ensuring it's relative to the directory.
        # os.path.join handles path separators correctly across OS.
        search_glob_pattern = os.path.join(absolute_directory_path, file_pattern)

        found_files = []
        if process_subdirectories:
            # glob.glob with recursive=True requires Python 3.5+.
            # Pipeline Pilot typically runs modern Python versions.
            found_files = glob.glob(search_glob_pattern, recursive=True)
        else:
            found_files = glob.glob(search_glob_pattern)

        if not found_files:
            self.logger.info(f"No files matching pattern '{file_pattern}' found in '{absolute_directory_path}'")
        else:
            self.logger.info(f"Found {len(found_files)} potential files.")

        # Filter out directories and ensure paths are absolute before outputting.
        # Sorting for deterministic output order.
        processed_count = 0
        for file_path in sorted(found_files):
            if os.path.isfile(file_path):
                absolute_file_path = os.path.abspath(file_path)
                self.output_record({'FilePath': absolute_file_path})
                self.logger.debug(f"Detected and outputted file: '{absolute_file_path}'")
                processed_count += 1
            else:
                self.logger.debug(f"Skipping non-file entry matching pattern: '{file_path}'")

        self.logger.info(f"Finished scanning. Total {processed_count} file(s) outputted.")


